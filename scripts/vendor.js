#!/usr/bin/env node
// Copies third-party browser assets out of node_modules into public/vendor so
// the app serves everything from its own origin. No CDN, no Google Fonts:
// a privacy tool shouldn't be leaking every user's IP and room visit to a
// third party, and a compromised CDN script would see plaintext before we
// encrypt it. Re-run with `npm run vendor` after bumping any of these deps.

const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const out = path.join(root, "public", "vendor");

const OUTFIT_WEIGHTS = [300, 400, 500, 600, 700, 800];
const MONO_WEIGHTS = [400, 500];

function copy(from, to) {
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.copyFileSync(from, to);
  console.log("  " + path.relative(root, to));
}

fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });

console.log("vendoring browser assets -> public/vendor");

// socket.io client. The server also serves this at /socket.io/socket.io.js,
// but vendoring it keeps the CSP script-src to a single predictable path.
copy(
  path.join(root, "node_modules/socket.io/client-dist/socket.io.min.js"),
  path.join(out, "socket.io.min.js")
);

// QR generator (replaces the unpinned cdnjs qrcodejs build)
copy(
  path.join(root, "node_modules/qrcode-generator/dist/qrcode.js"),
  path.join(out, "qrcode.js")
);

// Fonts, latin subset only
const faces = [];
for (const w of OUTFIT_WEIGHTS) {
  const file = `outfit-latin-${w}-normal.woff2`;
  copy(
    path.join(root, "node_modules/@fontsource/outfit/files", file),
    path.join(out, "fonts", file)
  );
  faces.push(face("Outfit", w, file));
}
for (const w of MONO_WEIGHTS) {
  const file = `jetbrains-mono-latin-${w}-normal.woff2`;
  copy(
    path.join(root, "node_modules/@fontsource/jetbrains-mono/files", file),
    path.join(out, "fonts", file)
  );
  faces.push(face("JetBrains Mono", w, file));
}

function face(family, weight, file) {
  return `@font-face {
  font-family: "${family}";
  font-style: normal;
  font-weight: ${weight};
  font-display: swap;
  src: url("/vendor/fonts/${file}") format("woff2");
}`;
}

const css = `/* Generated by scripts/vendor.js - do not edit by hand. */\n${faces.join(
  "\n"
)}\n`;
fs.writeFileSync(path.join(out, "fonts.css"), css);
console.log("  public/vendor/fonts.css");
console.log("done");
